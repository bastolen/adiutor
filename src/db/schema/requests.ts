/**
 * @file Drizzle schema for requests: what a company raises with the staff
 * (or, without a company, the staff's own internal requests), the people on
 * it (assigned or subscribed), the entries of its history (replies and
 * changes), the earlier versions of its edited texts, the people its texts
 * mention and the files attached to them. Requests are numbered from the
 * `requests.last_number` setting (`src/server/settings/`). The values of the
 * status, type, priority, side, kind and format columns live in
 * `src/lib/requests`.
 *
 * Conventions: every ID is a time-ordered UUIDv7 generated by Postgres (no
 * auto-increment), every foreign key has an index, and timestamps are stored
 * with time zone.
 */
import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  integer,
  pgTable,
  text,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

import {
  ASSIGNMENT_CHANGES,
  ATTACHMENT_CONTENT_TYPES,
  REQUEST_ENTRY_KINDS,
  REQUEST_PARTICIPANT_ROLES,
  REQUEST_PRIORITIES,
  REQUEST_SIDES,
  REQUEST_STATUSES,
  REQUEST_TEXT_FORMATS,
  SOLUTION_ANSWERS,
  WRITTEN_ENTRY_KINDS,
  WRITTEN_TEXT_FORMAT,
} from '../../lib/requests';
import { user } from './auth';
import { createdAt, id, oneOf, timestampTz } from './columns';
import { company } from './companies';

/** The kinds of entry that hold a text, as a list for a check constraint. */
const WRITTEN_KINDS = WRITTEN_ENTRY_KINDS.map((kind) => `'${kind}'`).join(', ');

/**
 * A kind of request the staff offer, which whoever raises a request picks:
 * the four built-in ones (Hotfix, Bug, Support, New feature) to begin with,
 * then whatever staff Admins add in Settings (decision 0027). A type is
 * never deleted: archived, it can't be picked any more, and the requests that
 * have it keep it.
 */
export const requestType = pgTable(
  'request_type',
  {
    id: id(),
    /**
     * What requests, their history and the list's `?type=` filter hold
     * (`REQUEST_TYPE_KEY_PATTERN`). Made from the name when the type is added
     * (`requestTypeKeyFromName`), and never changed or reused.
     */
    key: text('key').notNull(),
    /** Its name, one text for every language, like the staff name. */
    name: text('name').notNull(),
    /** What it's for, shown with it when a request is raised. */
    description: text('description').notNull(),
    /** The priority a request of this type starts with, until the staff change it. */
    startingPriority: text('starting_priority', { enum: REQUEST_PRIORITIES }).notNull(),
    /** Its place in every list of types, from 1. */
    position: integer('position').notNull(),
    /** When it was archived, or `null` while it can be picked. */
    archivedAt: timestampTz('archived_at'),
    createdAt: createdAt(),
    /**
     * When the staff last changed it, or `null` while it's as it was added
     * (setup names an unchanged built-in type in its language).
     */
    updatedAt: timestampTz('updated_at'),
  },
  (table) => [
    /** One type per key, which requests point at. */
    uniqueIndex('request_type_key_idx').on(table.key),
    /** One type per place, in the order every list shows. */
    uniqueIndex('request_type_position_idx').on(table.position),
    check('request_type_key_form', sql`${table.key} ~ '^[a-z0-9_]{1,40}$'`),
    oneOf('request_type_starting_priority_valid', table.startingPriority, REQUEST_PRIORITIES),
  ],
);

/**
 * A request a company raised with the staff, or the staff raised for it; or,
 * without a company, an internal request: the staff's own, which only the
 * staff read (decision 0048).
 */
export const request = pgTable(
  'request',
  {
    id: id(),
    /**
     * The number people see and quote ("AD-142" with the staff's prefix), and
     * the request's address (`/requests/142`). One series across Adiutor,
     * taken from the `requests.last_number` setting when the request is raised.
     */
    number: integer('number').notNull(),
    /**
     * The company it belongs to, or `null` for an internal request (decision
     * 0048), which only the staff read: a membership never counts for one
     * (`getInternalRequestPermissions`). It never changes.
     */
    companyId: uuid('company_id').references(() => company.id, { onDelete: 'cascade' }),
    /** One line saying what it's about. The staff can change it. */
    title: text('title').notNull(),
    /**
     * What was asked. Edited only through `editRequestDescription`, while the
     * request is open; each edit keeps the text it replaced as a
     * `request_text_version`.
     */
    description: text('description').notNull(),
    /** The format `description` is written in, so it's never read as another format. */
    descriptionFormat: text('description_format', { enum: REQUEST_TEXT_FORMATS })
      .notNull()
      .default(WRITTEN_TEXT_FORMAT),
    /** When the description was last edited, or `null` while it's as it was written. */
    descriptionEditedAt: timestampTz('description_edited_at'),
    /**
     * What kind of request it is, chosen by whoever raised it: a type's key.
     * The staff can change it.
     */
    type: text('type')
      .notNull()
      .references(() => requestType.key),
    /**
     * How urgent it is: the type's starting priority until the staff change
     * it. Only staff see it.
     */
    priority: text('priority', { enum: REQUEST_PRIORITIES }).notNull(),
    status: text('status', { enum: REQUEST_STATUSES }).notNull().default('open'),
    /**
     * When it was last reopened, while it's open again: set when a done or
     * cancelled request gets a status that's worked on, cleared when it's
     * done or cancelled again.
     */
    reopenedAt: timestampTz('reopened_at'),
    /** Who raised it, while their account exists. */
    createdBy: uuid('created_by').references(() => user.id, { onDelete: 'set null' }),
    /**
     * Which side raised it: someone at the company (also when a staff member
     * raised it for them, `createdOnBehalf`), or the staff (for the company,
     * or an internal request, which only the staff raise).
     */
    createdBySide: text('created_by_side', { enum: REQUEST_SIDES }).notNull(),
    /**
     * Whether a staff member raised it while signed in as whoever raised it
     * (decision 0028): `createdOnBehalfBy` for a request raised for someone,
     * `createdBy` otherwise. Kept once the staff member's account is gone, so
     * the request still says a staff member did it.
     */
    createdSignedInAs: boolean('created_signed_in_as').default(false).notNull(),
    /** The staff member who was signed in as whoever raised it, while their account exists. */
    createdSignedInAsStaffId: uuid('created_signed_in_as_staff_id').references(() => user.id, {
      onDelete: 'set null',
    }),
    /**
     * Whether a staff member raised it for `createdBy`, someone at the company
     * who asked them (decision 0047). Kept once the staff member's account is
     * gone, so the request still says a staff member raised it for them.
     */
    createdOnBehalf: boolean('created_on_behalf').default(false).notNull(),
    /** The staff member who raised it for `createdBy`, while their account exists. */
    createdOnBehalfBy: uuid('created_on_behalf_by').references(() => user.id, {
      onDelete: 'set null',
    }),
    /** When it was raised: the moment its number was taken (`raiseRequest`), not this default. */
    createdAt: createdAt(),
    /** When it was raised, replied to or changed last: what lists sort by. */
    lastActivityAt: timestampTz('last_activity_at').defaultNow().notNull(),
  },
  (table) => [
    /** Every request has its own number. */
    uniqueIndex('request_number_idx').on(table.number),
    /**
     * A company's requests by their last activity, and the internal requests
     * (`company_id is null`); also serves the company foreign key.
     */
    index('request_company_activity_idx').on(table.companyId, table.lastActivityAt, table.id),
    /** Every company's requests by their last activity, for the staff. */
    index('request_activity_idx').on(table.lastActivityAt, table.id),
    index('request_created_by_idx').on(table.createdBy),
    index('request_created_signed_in_as_staff_idx').on(table.createdSignedInAsStaffId),
    index('request_created_on_behalf_by_idx').on(table.createdOnBehalfBy),
    /** The requests of a type; also serves the type foreign key. */
    index('request_type_idx').on(table.type),
    oneOf('request_priority_valid', table.priority, REQUEST_PRIORITIES),
    oneOf('request_status_valid', table.status, REQUEST_STATUSES),
    oneOf('request_created_by_side_valid', table.createdBySide, REQUEST_SIDES),
    oneOf('request_description_format_valid', table.descriptionFormat, REQUEST_TEXT_FORMATS),
    /** A staff member is named only for a request raised while signed in as someone. */
    check(
      'request_created_signed_in_as_fits',
      sql`${table.createdSignedInAsStaffId} is null or ${table.createdSignedInAs}`,
    ),
    /**
     * A staff member is named only for a request raised for someone, and
     * that someone is at the company.
     */
    check(
      'request_created_on_behalf_fits',
      sql`(${table.createdOnBehalfBy} is null or ${table.createdOnBehalf}) and (not ${table.createdOnBehalf} or ${table.createdBySide} = 'company')`,
    ),
    /**
     * An internal request (without a company) is raised by the staff, so
     * it's never raised for someone at a company either.
     */
    check(
      'request_internal_by_staff',
      sql`${table.companyId} is not null or ${table.createdBySide} = 'staff'`,
    ),
  ],
);

/**
 * Someone on a request, in one role: assigned to it, or subscribed to it
 * (`REQUEST_PARTICIPANT_ROLES`). Someone with both roles has two rows.
 * Everyone on a request is who a notification about it reaches.
 *
 * - **An assignee** is a staff member who works on the request. A request
 *   can have several, or none. Only staff who work on requests are assigned
 *   (`mayBeAssigned`); someone who stops working on requests is removed from
 *   theirs, with an entry in each history, before their role, deactivation
 *   or deletion is saved (`unassignFrom`).
 * - **A subscriber** follows the request: anyone who can read it, from the
 *   staff or from its company. Whoever raises a request, replies to it or is
 *   mentioned in it is subscribed; someone who can no longer read it is taken
 *   off (`unsubscribeFrom`). Subscribing leaves nothing in the history.
 *
 * The rows go with the request or the account.
 */
export const requestParticipant = pgTable(
  'request_participant',
  {
    id: id(),
    requestId: uuid('request_id')
      .notNull()
      .references(() => request.id, { onDelete: 'cascade' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    /** What they're on the request as. */
    role: text('role', { enum: REQUEST_PARTICIPANT_ROLES }).notNull(),
    /** When they were assigned, or subscribed. */
    createdAt: createdAt(),
  },
  (table) => [
    /** Someone has a role on a request once; also serves the request foreign key. */
    uniqueIndex('request_participant_request_user_role_idx').on(
      table.requestId,
      table.userId,
      table.role,
    ),
    /** The requests someone is on, per role; also serves the user foreign key. */
    index('request_participant_user_idx').on(table.userId, table.role, table.requestId),
    oneOf('request_participant_role_valid', table.role, REQUEST_PARTICIPANT_ROLES),
  ],
);

/**
 * One entry in a request's history: a reply, an internal note only the staff
 * read, a change of its status, title,
 * type or priority, or a staff member assigned to it or removed from it. A
 * request's entries in ID order are its
 * conversation: IDs are time-ordered, and entries written in one change (a
 * reply and the status it sets) keep their order, which their creation times
 * can't say.
 */
export const requestEntry = pgTable(
  'request_entry',
  {
    id: id(),
    requestId: uuid('request_id')
      .notNull()
      .references(() => request.id, { onDelete: 'cascade' }),
    kind: text('kind', { enum: REQUEST_ENTRY_KINDS }).notNull(),
    /** Who wrote or changed it, while their account exists. */
    authorId: uuid('author_id').references(() => user.id, { onDelete: 'set null' }),
    /** Which side they acted as, kept so the history still says so once the account is gone. */
    authorSide: text('author_side', { enum: REQUEST_SIDES }).notNull(),
    /**
     * Whether a staff member wrote or changed it while signed in as the
     * author (decision 0028). Kept once the staff member's account is gone.
     */
    signedInAs: boolean('signed_in_as').default(false).notNull(),
    /** The staff member who was signed in as the author, while their account exists. */
    signedInAsStaffId: uuid('signed_in_as_staff_id').references(() => user.id, {
      onDelete: 'set null',
    }),
    /**
     * A reply's or a note's text; `null` for a change. Edited only by its
     * author, through `editReply`, while the request is open; each edit keeps
     * the text it replaced as a `request_text_version`.
     */
    body: text('body'),
    /** The format `body` is written in, so it's never read as another format. */
    bodyFormat: text('body_format', { enum: REQUEST_TEXT_FORMATS })
      .notNull()
      .default(WRITTEN_TEXT_FORMAT),
    /** When a reply or note was last edited, or `null` while it's as it was written. */
    editedAt: timestampTz('edited_at'),
    /** What a change replaced: a status, type or priority, or the earlier title. */
    fromValue: text('from_value'),
    /**
     * What a change set; `null` for a reply. For an `assignee` entry, whether
     * its subject was assigned or removed (`ASSIGNMENT_CHANGES`).
     */
    toValue: text('to_value'),
    /**
     * Who an `assignee` entry is about: the staff member assigned or removed,
     * while their account exists. `null` for every other kind, and once the
     * account is gone: the history then names them in general terms, and
     * keeps no ID of a deleted account.
     */
    subjectUserId: uuid('subject_user_id').references(() => user.id, { onDelete: 'set null' }),
    /**
     * When it was written. The services set the moment of the change (the
     * clock once the request is locked), not this default, which is when the
     * transaction started: an entry that waited for another would seem older.
     */
    createdAt: createdAt(),
  },
  (table) => [
    /** A request's entries in order; also serves the request foreign key. */
    index('request_entry_request_idx').on(table.requestId, table.id),
    index('request_entry_author_idx').on(table.authorId),
    index('request_entry_subject_idx').on(table.subjectUserId),
    index('request_entry_signed_in_as_staff_idx').on(table.signedInAsStaffId),
    /**
     * A reply or a note has a text and no new value; a change has a new value
     * and no text.
     */
    check(
      'request_entry_kind_fits_values',
      sql`(${table.kind} in (${sql.raw(WRITTEN_KINDS)})) = (${table.body} is not null) and (${table.kind} in (${sql.raw(WRITTEN_KINDS)})) = (${table.toValue} is null)`,
    ),
    /**
     * An assignment entry says whether its subject was assigned or removed;
     * no other kind has a subject.
     */
    check(
      'request_entry_assignment_fits_values',
      sql`case when ${table.kind} = 'assignee' then ${table.toValue} in (${sql.raw(
        ASSIGNMENT_CHANGES.map((change) => `'${change}'`).join(', '),
      )}) else ${table.subjectUserId} is null end`,
    ),
    oneOf('request_entry_kind_valid', table.kind, REQUEST_ENTRY_KINDS),
    oneOf('request_entry_author_side_valid', table.authorSide, REQUEST_SIDES),
    oneOf('request_entry_body_format_valid', table.bodyFormat, REQUEST_TEXT_FORMATS),
    /** A staff member is named only for an entry made while signed in as someone. */
    check(
      'request_entry_signed_in_as_fits',
      sql`${table.signedInAsStaffId} is null or ${table.signedInAs}`,
    ),
  ],
);

/**
 * Someone a request's text mentions: its description, or one of its replies.
 * The text itself holds only a marker with this row's ID (`storedMentionMarker`
 * in `src/lib/requests`), never a name or a user ID: who is mentioned is read
 * from here when the text is shown, so a mention follows a renamed account
 * and forgets a deleted one. A text mentions someone once, however often it
 * names them. The rows go with the request or the reply.
 */
export const requestMention = pgTable(
  'request_mention',
  {
    id: id(),
    requestId: uuid('request_id')
      .notNull()
      .references(() => request.id, { onDelete: 'cascade' }),
    /** The reply that mentions them; `null` for the request's description. */
    entryId: uuid('entry_id').references(() => requestEntry.id, { onDelete: 'cascade' }),
    /** Who is mentioned, while their account exists. */
    userId: uuid('user_id').references(() => user.id, { onDelete: 'set null' }),
    /** The side they were on when they were mentioned, kept so the text still says so once the account is gone. */
    side: text('side', { enum: REQUEST_SIDES }).notNull(),
    /** When they were mentioned. */
    createdAt: createdAt(),
  },
  (table) => [
    /** A request's mentions; also serves the request foreign key. */
    index('request_mention_request_idx').on(table.requestId),
    index('request_mention_entry_idx').on(table.entryId),
    /** Where someone is mentioned; also serves the user foreign key. */
    index('request_mention_user_idx').on(table.userId),
    oneOf('request_mention_side_valid', table.side, REQUEST_SIDES),
  ],
);

/**
 * A text of a request as it was before an edit: its description, or one of
 * its replies. One row per edit, holding the text the edit replaced, so the
 * staff can read every earlier version (`listTextVersions`); nobody at the
 * company can. Its mentions are kept as plain "@Name" text, since the
 * mention rows belong to the text as it is now. The rows go with the
 * request or the reply.
 */
export const requestTextVersion = pgTable(
  'request_text_version',
  {
    id: id(),
    requestId: uuid('request_id')
      .notNull()
      .references(() => request.id, { onDelete: 'cascade' }),
    /** The reply it's a version of; `null` for the request's description. */
    entryId: uuid('entry_id').references(() => requestEntry.id, { onDelete: 'cascade' }),
    /** The text as it was before the edit. */
    body: text('body').notNull(),
    /** The format `body` is written in, so it's never read as another format. */
    bodyFormat: text('body_format', { enum: REQUEST_TEXT_FORMATS }).notNull(),
    /** Who edited it away, while their account exists. */
    editedBy: uuid('edited_by').references(() => user.id, { onDelete: 'set null' }),
    /** The side they edited it as, kept so the versions still say so once the account is gone. */
    editedBySide: text('edited_by_side', { enum: REQUEST_SIDES }).notNull(),
    /**
     * Whether a staff member made the edit while signed in as `editedBy`
     * (decision 0028). Kept once the staff member's account is gone.
     */
    signedInAs: boolean('signed_in_as').default(false).notNull(),
    /** The staff member who was signed in as `editedBy`, while their account exists. */
    signedInAsStaffId: uuid('signed_in_as_staff_id').references(() => user.id, {
      onDelete: 'set null',
    }),
    /** When it was edited away: the moment of the edit (`CHANGE_MOMENT`). */
    createdAt: createdAt(),
  },
  (table) => [
    /** A request's versions; also serves the request foreign key. */
    index('request_text_version_request_idx').on(table.requestId, table.id),
    index('request_text_version_entry_idx').on(table.entryId),
    index('request_text_version_edited_by_idx').on(table.editedBy),
    index('request_text_version_signed_in_as_staff_idx').on(table.signedInAsStaffId),
    oneOf('request_text_version_body_format_valid', table.bodyFormat, REQUEST_TEXT_FORMATS),
    oneOf('request_text_version_edited_by_side_valid', table.editedBySide, REQUEST_SIDES),
    /** A staff member is named only for an edit made while signed in as someone. */
    check(
      'request_text_version_signed_in_as_fits',
      sql`${table.signedInAsStaffId} is null or ${table.signedInAs}`,
    ),
  ],
);

/**
 * A file attached to a request's text (decision 0044): its description, a
 * reply or an internal note. The file itself is kept in the storage chosen
 * for attachments, under a key made from this row's ID (`attachmentKey`);
 * this row is how it's found, named and checked. A file is uploaded on its
 * own first (unsent: no request yet) and claimed by the text it's sent with
 * (`claimAttachments`); one left unsent is purged after a day, file and row.
 * A removed file keeps its row, so its place in the text says who removed
 * it, while the file itself is deleted. The rows go with the request or the
 * text.
 */
export const requestAttachment = pgTable(
  'request_attachment',
  {
    id: id(),
    /** The request it was sent with; `null` while it's unsent. */
    requestId: uuid('request_id').references(() => request.id, { onDelete: 'cascade' }),
    /** The reply or note it belongs to; `null` for the description (or while unsent). */
    entryId: uuid('entry_id').references(() => requestEntry.id, { onDelete: 'cascade' }),
    /** Who uploaded it, while their account exists. */
    uploadedBy: uuid('uploaded_by').references(() => user.id, { onDelete: 'set null' }),
    /**
     * Whether a staff member uploaded it while signed in as `uploadedBy`
     * (decision 0028). Kept once the staff member's account is gone.
     */
    signedInAs: boolean('signed_in_as').default(false).notNull(),
    /** The staff member who was signed in as `uploadedBy`, while their account exists. */
    signedInAsStaffId: uuid('signed_in_as_staff_id').references(() => user.id, {
      onDelete: 'set null',
    }),
    /** Its name, cleaned (`cleanAttachmentName`), with an extension on the allow-list. */
    name: text('name').notNull(),
    /** The type it's stored and served as, from the allow-list (`ATTACHMENT_TYPES`). */
    contentType: text('content_type').notNull(),
    /** Its size in bytes. */
    size: integer('size').notNull(),
    /** When the upload started. */
    createdAt: createdAt(),
    /** When its file was stored; `null` while it's being written (or if that failed). */
    uploadedAt: timestampTz('uploaded_at'),
    /** When it was removed; its file is deleted then. */
    removedAt: timestampTz('removed_at'),
    /** Who removed it, while their account exists. */
    removedBy: uuid('removed_by').references(() => user.id, { onDelete: 'set null' }),
    /** Whether a staff member removed it while signed in as `removedBy`. */
    removedSignedInAs: boolean('removed_signed_in_as').default(false).notNull(),
    /** The staff member who was signed in as `removedBy`, while their account exists. */
    removedSignedInAsStaffId: uuid('removed_signed_in_as_staff_id').references(() => user.id, {
      onDelete: 'set null',
    }),
    /** When a removed file's bytes were deleted from storage; the cleanup job tries again until then. */
    fileDeletedAt: timestampTz('file_deleted_at'),
  },
  (table) => [
    /** A request's files, by text; also serves the request foreign key. */
    index('request_attachment_request_idx').on(table.requestId, table.entryId),
    index('request_attachment_entry_idx').on(table.entryId),
    /** What someone uploaded lately (the day's total); also serves the uploader foreign key. */
    index('request_attachment_uploaded_by_idx').on(table.uploadedBy, table.createdAt),
    index('request_attachment_signed_in_as_staff_idx').on(table.signedInAsStaffId),
    index('request_attachment_removed_by_idx').on(table.removedBy),
    index('request_attachment_removed_signed_in_as_staff_idx').on(table.removedSignedInAsStaffId),
    /** The unsent files the cleanup job purges. */
    index('request_attachment_unsent_idx')
      .on(table.createdAt)
      .where(sql`${table.requestId} is null`),
    oneOf('request_attachment_content_type_valid', table.contentType, ATTACHMENT_CONTENT_TYPES),
    check('request_attachment_size_fits', sql`${table.size} > 0`),
    /** A reply's or note's file belongs to that reply's request. */
    check(
      'request_attachment_entry_fits',
      sql`${table.entryId} is null or ${table.requestId} is not null`,
    ),
    /** Only a stored file is sent, and only a sent one is removed. */
    check(
      'request_attachment_sent_fits',
      sql`(${table.requestId} is null or ${table.uploadedAt} is not null) and (${table.removedAt} is null or ${table.requestId} is not null)`,
    ),
    /** A staff member is named only for an upload made while signed in as someone. */
    check(
      'request_attachment_signed_in_as_fits',
      sql`${table.signedInAsStaffId} is null or ${table.signedInAs}`,
    ),
    /** Who removed it, and its deleted file, only for a removed one. */
    check(
      'request_attachment_removed_fits',
      sql`${table.removedAt} is not null or (${table.removedBy} is null and not ${table.removedSignedInAs} and ${table.fileDeletedAt} is null)`,
    ),
    check(
      'request_attachment_removed_signed_in_as_fits',
      sql`${table.removedSignedInAsStaffId} is null or ${table.removedSignedInAs}`,
    ),
  ],
);

/**
 * A link in an email that answers a solution the staff sent (decision 0033):
 * one per person the email went to and proposal, so Approve and Deny work
 * without signing in, once, only for that person and that proposal. Only the
 * token's hash is stored. A link is used up by its answer, and goes stale
 * when it expires or the request no longer waits for that proposal. The rows
 * go with the request, the person or the proposal.
 */
export const requestAnswerLink = pgTable(
  'request_answer_link',
  {
    id: id(),
    requestId: uuid('request_id')
      .notNull()
      .references(() => request.id, { onDelete: 'cascade' }),
    /** Who the email went to, and whose answer the link gives. */
    userId: uuid('user_id')
      .notNull()
      .references(() => user.id, { onDelete: 'cascade' }),
    /** The status entry that made the request wait for approval: the proposal it answers. */
    proposalEntryId: uuid('proposal_entry_id')
      .notNull()
      .references(() => requestEntry.id, { onDelete: 'cascade' }),
    /** The token's SHA-256 (`hashToken`); the token itself is only ever in the email. */
    tokenHash: text('token_hash').notNull(),
    /** When it stops working, if it's still unused. */
    expiresAt: timestampTz('expires_at').notNull(),
    /** When its answer was given, or `null` while it's unused. */
    usedAt: timestampTz('used_at'),
    /** The answer it gave, once used. */
    answer: text('answer', { enum: SOLUTION_ANSWERS }),
    createdAt: createdAt(),
  },
  (table) => [
    uniqueIndex('request_answer_link_token_idx').on(table.tokenHash),
    /** A request's links; also serves the request foreign key. */
    index('request_answer_link_request_idx').on(table.requestId),
    index('request_answer_link_user_idx').on(table.userId),
    index('request_answer_link_proposal_idx').on(table.proposalEntryId),
    oneOf('request_answer_link_answer_valid', table.answer, SOLUTION_ANSWERS),
    /** An answer exactly when it's used. */
    check(
      'request_answer_link_used_fits',
      sql`(${table.usedAt} is null) = (${table.answer} is null)`,
    ),
  ],
);
